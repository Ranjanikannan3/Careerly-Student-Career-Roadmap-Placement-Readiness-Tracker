/**
 * Resolves the single masterclass video for any course or track
 */
export function getCourseMasterclass(courseKey, skillId) {
  const norm = (courseKey || "").trim();
  const id = (skillId || "").trim();

  let video = COURSE_MASTERCLASS_VIDEOS[norm]
    || COURSE_MASTERCLASS_VIDEOS[id]
    || COURSE_MASTERCLASS_VIDEOS[norm.toLowerCase()]
    || COURSE_MASTERCLASS_VIDEOS[id.toLowerCase()];

  if (!video) {
    const k = (norm + " " + id).toLowerCase();
    if (k.includes("java") && !k.includes("script")) video = COURSE_MASTERCLASS_VIDEOS["Java"];
    else if (k.includes("python")) video = COURSE_MASTERCLASS_VIDEOS["Python"];
    else if (k.includes("c++") || k.includes("cpp")) video = COURSE_MASTERCLASS_VIDEOS["C++"];
    else if (k.includes("javascript") || k.includes("js")) video = COURSE_MASTERCLASS_VIDEOS["JavaScript"];
    else if (k.includes("html") || k.includes("css")) video = COURSE_MASTERCLASS_VIDEOS["HTML & CSS"];
    else if (k.includes("sql") || k.includes("database")) video = COURSE_MASTERCLASS_VIDEOS["SQL"];
    else if (k.includes("data structure") || k.includes("ds")) video = COURSE_MASTERCLASS_VIDEOS["Data Structures"];
    else if (k.includes("algorithm") || k.includes("algo")) video = COURSE_MASTERCLASS_VIDEOS["Algorithms"];
    else if (k.includes("quant") || k.includes("aptitude") || k.includes("math")) video = COURSE_MASTERCLASS_VIDEOS["Quantitative Aptitude"];
    else if (k.includes("logical") || k.includes("reasoning") || k.includes("puzzle")) video = COURSE_MASTERCLASS_VIDEOS["Logical Reasoning"];
    else if (k.includes("verbal") || k.includes("english") || k.includes("grammar")) video = COURSE_MASTERCLASS_VIDEOS["Verbal Ability"];
    else if (k.includes("project") || k.includes("portfolio")) video = COURSE_MASTERCLASS_VIDEOS["Projects"];
    else if (k.includes("comm") || k.includes("speak") || k.includes("gd")) video = COURSE_MASTERCLASS_VIDEOS["Communication"];
    else if (k.includes("resume") || k.includes("cv")) video = COURSE_MASTERCLASS_VIDEOS["Resume"];
    else if (k.includes("interview") || k.includes("hr")) video = COURSE_MASTERCLASS_VIDEOS["Interview Preparation"];
    else if (k.includes("fullstack") || k.includes("mern") || k.includes("web") || k.includes("react")) video = COURSE_MASTERCLASS_VIDEOS["Full Stack Web"];
    else if (k.includes("ai") || k.includes("machine") || k.includes("ml")) video = COURSE_MASTERCLASS_VIDEOS["AI & Machine Learning"];
    else if (k.includes("data science") || k.includes("analytics")) video = COURSE_MASTERCLASS_VIDEOS["Data Science"];
    else if (k.includes("cloud") || k.includes("devops") || k.includes("aws")) video = COURSE_MASTERCLASS_VIDEOS["Cloud & DevOps"];
    else if (k.includes("cyber") || k.includes("security") || k.includes("hack")) video = COURSE_MASTERCLASS_VIDEOS["Cybersecurity"];
    else video = COURSE_MASTERCLASS_VIDEOS["Java"];
  }

  const searchQuery = encodeURIComponent(`${norm || id || "Full Course"} placement masterclass tutorial full course`);
  const googleQuery = encodeURIComponent(`${norm || id || "Course"} syllabus interview notes`);

  return {
    ...video,
    courseName: norm || id || "Course",
    watchUrl: `https://www.youtube.com/watch?v=${video.embedId}`,
    embedUrl: `https://www.youtube.com/embed/${video.embedId}?rel=0&modestbranding=1&enablejsapi=1`,
    youtubeSearchUrl: `https://www.youtube.com/results?search_query=${searchQuery}`,
    googleSearchUrl: `https://www.google.com/search?q=${googleQuery}`
  };
}

