/**
 * Returns exactly 10 placement questions for any topic in any course
 */
export function getTenQuestionsForTopic(topicName, skillName, moduleTitle) {
  const curated = TOPIC_TEN_QUESTION_BANKS[topicName];
  if (curated && Array.isArray(curated) && curated.length === 10) {
    return curated;
  }

  // If partially curated (e.g. 2 questions), keep them and fill up to exactly 10
  if (curated && Array.isArray(curated) && curated.length > 0) {
    const generated = buildTenPlacementQuestions(topicName, skillName, moduleTitle);
    const combined = [...curated];
    for (let i = combined.length; i < 10; i++) {
      combined.push(generated[i]);
    }
    return combined;
  }

  return buildTenPlacementQuestions(topicName, skillName, moduleTitle);
}

// Backward compatibility alias for single topic quiz lookup
export const TOPIC_QUIZZES = new Proxy(TOPIC_TEN_QUESTION_BANKS, {
  get(target, prop) {
    if (typeof prop === "string" && target[prop]) {
      return target[prop];
    }
    if (typeof prop === "string") {
      return buildTenPlacementQuestions(prop, "Core Track", "Fundamentals");
    }
    return undefined;
  }
});

